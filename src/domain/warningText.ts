// The health warning statement required on every alcohol beverage label,
// 27 CFR 16.21. The heading must be in capital letters and bold (16.22).
export const WARNING_HEADER = 'GOVERNMENT WARNING:';

export const WARNING_BODY =
  '(1) According to the Surgeon General, women should not drink alcoholic beverages during pregnancy because of the risk of birth defects. ' +
  '(2) Consumption of alcoholic beverages impairs your ability to drive a car or operate machinery, and may cause health problems.';

export const WARNING_FULL = `${WARNING_HEADER} ${WARNING_BODY}`;
